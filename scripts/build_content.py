#!/usr/bin/env python3
"""Build Bahala Na? content: per-card JSON files + cards-bundle.js (§C.6 pipeline)."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from content_a import CH1, CH2
from content_b import CH3_ROLE, CH3_SHARED, CH3_SINGIL
from content_c import CH4, ENDINGS, ECHOES, FINAL_ASKS, BACKGROUNDS, ERAS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CARDS_DIR = os.path.join(ROOT, "content", "cards")


def main():
    os.makedirs(CARDS_DIR, exist_ok=True)
    cards = CH1 + CH2 + CH3_ROLE + CH3_SHARED + CH3_SINGIL + CH4
    ids = set()
    for c in cards:
        assert c["id"] not in ids, f"duplicate card id: {c['id']}"
        ids.add(c["id"])
        with open(os.path.join(CARDS_DIR, c["id"] + ".json"), "w", encoding="utf-8") as f:
            json.dump(c, f, ensure_ascii=False, indent=2)
    print(f"wrote {len(cards)} card JSON files")

    extras = {
        "endings.json": ENDINGS,
        "echoes.json": ECHOES,
        "final_asks.json": FINAL_ASKS,
        "backgrounds.json": BACKGROUNDS,
        "eras.json": ERAS,
    }
    for name, data in extras.items():
        with open(os.path.join(ROOT, "content", name), "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    print("wrote endings/echoes/final_asks/backgrounds/eras")

    bundle = {
        "cards": cards,
        "endings": ENDINGS,
        "echoes": ECHOES,
        "finalAsks": FINAL_ASKS,
        "backgrounds": BACKGROUNDS,
        "eras": ERAS,
    }
    with open(os.path.join(ROOT, "content", "cards-bundle.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/build_content.py — do not edit by hand.\n")
        f.write("window.BAHALANA_CONTENT = ")
        json.dump(bundle, f, ensure_ascii=False)
        f.write(";\n")
    print("wrote content/cards-bundle.js")


if __name__ == "__main__":
    main()
